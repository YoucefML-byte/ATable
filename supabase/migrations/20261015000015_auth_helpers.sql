-- Authentication helpers. Bible: vol. 02 AUTH-01 CA2, AUTH-02; vol. 05 §4.
-- * Progressive delay after 5 failed 2FA codes, kept in the database (not in a cookie the user
--   could delete). Only an aal2 session can reset it.
-- * Device enrolment by the owner without the secret key: only the SHA-256 of the device secret
--   reaches the database.

create table private.mfa_failures (
  user_id      uuid primary key references auth.users (id) on delete cascade,
  failures     integer not null default 0,
  last_failure timestamptz not null default now()
);

-- Seconds to wait before the next attempt (0 = allowed).
create or replace function public.auth_mfa_wait_seconds()
returns integer
language sql stable security definer set search_path = ''
as $$
  select coalesce((
    select greatest(0, ceil(extract(epoch from
      (f.last_failure + make_interval(secs => least(900, 15 * power(2, f.failures - 5)))) - now()))::integer)
    from private.mfa_failures f
    where f.user_id = (select auth.uid()) and f.failures >= 5
  ), 0);
$$;

create or replace function public.auth_register_mfa_failure()
returns integer
language plpgsql security definer set search_path = ''
as $$
begin
  if (select auth.uid()) is null then
    raise exception using errcode = 'P0001', message = 'UNAUTHENTICATED';
  end if;
  insert into private.mfa_failures as f (user_id, failures, last_failure)
  values ((select auth.uid()), 1, now())
  on conflict (user_id) do update set failures = f.failures + 1, last_failure = now();
  return public.auth_mfa_wait_seconds();
end;
$$;

create or replace function public.auth_reset_mfa_failures()
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if coalesce((select auth.jwt() ->> 'aal'), '') <> 'aal2' then
    raise exception using errcode = 'P0001', message = 'FORBIDDEN';
  end if;
  delete from private.mfa_failures where user_id = (select auth.uid());
end;
$$;

-- Owner enrols the current device (AUTH-02). Returns the device id.
create or replace function public.owner_enroll_device(p_shop_id uuid, p_name text, p_secret_hash text)
returns uuid
language plpgsql security definer set search_path = ''
as $$
declare
  v_id uuid;
begin
  if not private.has_perm(p_shop_id, 'owner') then
    raise exception using errcode = 'P0001', message = 'FORBIDDEN';
  end if;
  if p_secret_hash !~ '^[0-9a-f]{64}$' or char_length(btrim(p_name)) not between 1 and 40 then
    raise exception using errcode = 'P0001', message = 'BAD_REQUEST';
  end if;
  insert into public.devices (shop_id, name, secret_hash, enrolled_by)
  values (p_shop_id, btrim(p_name), p_secret_hash, private.current_member_id(p_shop_id))
  returning id into v_id;
  perform private.audit(p_shop_id, 'device.enroll', 'device', v_id, jsonb_build_object('name', btrim(p_name)));
  return v_id;
end;
$$;

-- Table creation in batch ("Tables 1 to 20 in the Room zone", TAB-01). Tokens are generated by
-- the server (Node crypto) and passed in.
create or replace function public.owner_create_tables(p_shop_id uuid, p_tables jsonb)
returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  v_item  jsonb;
  v_id    uuid;
  v_count integer := 0;
  v_pos   integer;
begin
  if not private.has_perm(p_shop_id, 'owner') then
    raise exception using errcode = 'P0001', message = 'FORBIDDEN';
  end if;
  if jsonb_typeof(p_tables) <> 'array' or jsonb_array_length(p_tables) not between 1 and 200 then
    raise exception using errcode = 'P0001', message = 'BAD_REQUEST';
  end if;
  select coalesce(max(position), 0) into v_pos from public.dining_tables where shop_id = p_shop_id;
  for v_item in select value from jsonb_array_elements(p_tables) loop
    v_pos := v_pos + 1;
    insert into public.dining_tables (shop_id, label, zone, seats, position)
    values (p_shop_id, btrim(v_item ->> 'label'), nullif(btrim(coalesce(v_item ->> 'zone', '')), ''),
            nullif(v_item ->> 'seats', '')::smallint, v_pos)
    returning id into v_id;
    if coalesce(v_item ->> 'token', '') !~ '^[A-Za-z0-9_-]{22,64}$' then
      raise exception using errcode = 'P0001', message = 'BAD_REQUEST';
    end if;
    insert into public.table_tokens (shop_id, table_id, token, created_by)
    values (p_shop_id, v_id, v_item ->> 'token', private.current_member_id(p_shop_id));
    v_count := v_count + 1;
  end loop;
  return v_count;
end;
$$;

revoke all on function public.auth_mfa_wait_seconds() from public, anon;
revoke all on function public.auth_register_mfa_failure() from public, anon;
revoke all on function public.auth_reset_mfa_failures() from public, anon;
revoke all on function public.owner_enroll_device(uuid, text, text) from public, anon;
revoke all on function public.owner_create_tables(uuid, jsonb) from public, anon;
grant execute on function public.auth_mfa_wait_seconds() to authenticated;
grant execute on function public.auth_register_mfa_failure() to authenticated;
grant execute on function public.auth_reset_mfa_failures() to authenticated;
grant execute on function public.owner_enroll_device(uuid, text, text) to authenticated;
grant execute on function public.owner_create_tables(uuid, jsonb) to authenticated;
