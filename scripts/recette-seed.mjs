// Writes supabase/recette/.generated/10-recette.sql for the staging ("recette") database, from
// environment variables set by the GitHub workflow (never committed):
//   RECETTE_PREFIX         e.g. "atable-yml": hosts atable-yml-bistrot.vercel.app, -lounge, -pro, -console
//   RECETTE_DEMO_PASSWORD  password of the three demo accounts (12 characters or more)
// The demo accounts get this password instead of the public one of the README, and their TOTP
// factors are removed: each tester enrols their own authenticator app at first login.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const prefix = (process.env.RECETTE_PREFIX ?? '').trim().toLowerCase();
const password = process.env.RECETTE_DEMO_PASSWORD ?? '';

const fail = (message) => {
  console.error(`::error::${message}`);
  process.exit(1);
};
if (!/^[a-z0-9](?:[a-z0-9-]{1,38}[a-z0-9])$/.test(prefix)) {
  fail(
    'RECETTE_PREFIX doit contenir 3 à 40 lettres minuscules, chiffres ou tirets (ex. atable-yml).',
  );
}
if (password.length < 12 || password.includes('$recette$')) {
  fail('RECETTE_DEMO_PASSWORD doit faire au moins 12 caractères.');
}

const host = (name) => `${prefix}-${name}.vercel.app`;
const sql = `-- Generated by scripts/recette-seed.mjs — do not commit.
update public.shop_domains set hostname = '${host('bistrot')}' where hostname = 'bistrot.localhost';
update public.shop_domains set hostname = '${host('lounge')}' where hostname = 'lounge.localhost';

update auth.users
   set encrypted_password = extensions.crypt($recette$${password}$recette$, extensions.gen_salt('bf')),
       updated_at = now()
 where email in ('admin@atable.test', 'karim@bistrot.test', 'samia@lounge.test');

delete from auth.mfa_factors
 where user_id in (select id from auth.users
                    where email in ('admin@atable.test', 'karim@bistrot.test', 'samia@lounge.test'));
`;

const dir = join(process.cwd(), 'supabase', 'recette', '.generated');
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, '10-recette.sql'), sql, { mode: 0o600 });
console.log(
  `Staging seed written for ${host('bistrot')}, ${host('lounge')}, ${host('pro')}, ${host('console')}.`,
);
